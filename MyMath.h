#pragma once

// Пошук першого входження пари сусідніх букв "aa", "bb" або "cc" у рядку s.
// Повертає вказівник на початок пари або nullptr, якщо пари немає
const char* FindPair(const char* s);

// З'ясовує, чи є у рядку s пара сусідніх букв "aa" або "bb" або "cc"
bool HasPair(const char* s);

// Заміна кожної пари сусідніх букв "aa" або "bb" або "cc" трійкою зірочок "***".
// Рядок s не змінюється; результат повертається як новий рядок (звільняти delete[])
char* Change(const char* s);
